// Planner data for STM32 boards. Every row comes from stm32duino 3.0.0: the
// board's variant file gives the pin behind each header position, and its
// PeripheralPins.c gives the alternate functions of that port pin. Complementary
// timer outputs (CHxN) are left out, and a bus whose signals are not all on the
// mapped headers is dropped. Nucleo-64 header maps were matched against Zephyr
// v4.2.0 arduino_r3_connector.dtsi.

