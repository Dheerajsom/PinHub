export type Stm32BoardId = keyof typeof stm32Boards;

const stm32duino = "https://github.com/stm32duino/Arduino_Core_STM32/blob/3.0.0/variants";

function stm32FunctionData(entry: Stm32Board, table: PinFunctionTable): PinFunctionData {
  const base = `${stm32duino}/${encodeURI(entry.dir).replace(/\(/g, "%28").replace(/\)/g, "%29")}`;
  const used = new Set(Object.values(table).flatMap((row) => row.flags ?? []));
  const header = `variant_${entry.variant}.h`;
  const flagNotes: PinFunctionData["flagNotes"] = {};
  if (used.has("onboard-led")) {
    flagNotes["onboard-led"] = `stm32duino ${header}: LED_BUILTIN is ${entry.led}, so the onboard LED is driven from this pin.`;
  }
  if (used.has("usb")) {
    flagNotes.usb = entry.serial
      ? `stm32duino ${header}: “Default pin used for 'Serial' instance (ex: ST-Link)”. ${entry.serial} carry the ST-LINK virtual COM port.`
      : `stm32duino variant comments name PA11 “USB DM” and PA12 “USB DP”. These pins carry the board's USB connector.`;
  }
  return {
    sources: [
      {
        label: `stm32duino 3.0.0 ${entry.peripheralPins}: alternate functions of each port pin`,
        url: `${base}/${entry.peripheralPins}`,
        type: "Docs",
      },
      {
        label: `stm32duino 3.0.0 variant_${entry.variant}.cpp: the port pin behind each Arduino pin`,
        url: `${base}/variant_${entry.variant}.cpp`,
        type: "Docs",
      },
      {
        label: `stm32duino 3.0.0 ${header}: default Serial, Wire, and SPI pins`,
        url: `${base}/${header}`,
        type: "Docs",
      },
    ],
    mux: {
      model: "fixed",
      note: "Each STM32 port pin selects one alternate function, so a bus can only use the pins stm32duino's PeripheralPins table lists for it. Chip select is any free GPIO driven by software.",
      softwareCs: true,
    },
    flagNotes,
    exports: ["arduino", "json"],
  };
}

/** The planner fields for one STM32 board in the catalog. */
export function stm32PinFunctions(
  boardId: Stm32BoardId,
  pinout: Pinout,
): { pinout: Pinout; pinFunctions: PinFunctionData } {
  const entry: Stm32Board = stm32Boards[boardId];
  const table = tableFromRows(entry.pins);
  return { pinout: withPinFunctions(pinout, table), pinFunctions: stm32FunctionData(entry, table) };
}
