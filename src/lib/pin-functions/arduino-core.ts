// Planner data for boards whose pin functions come from an Arduino core's
// variant files. These list the Serial, Wire, and SPI ports the core actually
// sets up, the PWM timer behind each pin, and the ADC and DAC channels, so a
// plan matches what the board's libraries do out of the box. A chip that can
// remap a bus in code may reach more pins than this; PinHub plans only these.

