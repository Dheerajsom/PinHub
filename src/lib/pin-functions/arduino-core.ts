export type ArduinoCoreBoardId = keyof typeof arduinoCoreBoards;

function coreData(id: string, entry: CoreBoard, used: Set<string>): PinFunctionData {
  if (entry.family === "custom") {
    const custom = customFamilies[id];
    const led: PinFunctionData["flagNotes"] = used.has("onboard-led")
      ? { "onboard-led": `Arduino: ${ledReference} The core defines LED_BUILTIN as ${entry.led}.` }
      : {};
    return { ...custom, flagNotes: { ...custom.flagNotes, ...led } };
  }
  const family = coreFamilies[entry.family];
  const repo = coreRepos[entry.repo ?? entry.family];
  const flagNotes: PinFunctionData["flagNotes"] = {};
  if (used.has("usb") && family.usb) flagNotes.usb = family.usb;
  if (used.has("onboard-led")) {
    flagNotes["onboard-led"] = `Arduino: ${ledReference} The core variant defines LED_BUILTIN as ${entry.led}.`;
  }
  if (entry.family === "esp8266" && used.has("strapping")) {
    flagNotes.strapping =
      "ESP8266 Arduino: “The ESP module checks at every boot the Pins 0, 2 and 15. based on them its boots in different modes”.";
  }
  if (used.has("input-only")) {
    flagNotes["input-only"] =
      entry.family === "esp8266"
        ? "ESP8266 Arduino: “ESP8266 has a single ADC channel available to users.” A0 is that ADC pin, not a GPIO."
        : "ATmega328P datasheet: “ADC7:6 serve as analog inputs to the A/D converter.” They have no digital input or output.";
  }
  const common: PinFunctionData["sources"] =
    entry.family === "esp8266"
      ? [{ label: `${repo.name} variants/generic/common.h: SPI pins`, url: `${repo.url}/generic/common.h`, type: "Docs" }]
      : [];
  return {
    sources: [
      ...family.files.map((file) => ({
        label: `${repo.name} variants/${entry.variant}/${file}`,
        url: `${repo.url}/${entry.variant}/${file}`,
        type: "Docs" as const,
      })),
      ...common,
    ],
    mux: { model: "fixed", note: `${family.note} ${softwareCsNote}`, softwareCs: family.softwareCs },
    flagNotes,
    exports: [...family.exports],
  };
}

/** The planner fields for one board backed by an Arduino core variant. */
export function arduinoCorePinFunctions(
  boardId: ArduinoCoreBoardId,
  pinout: Pinout,
): { pinout: Pinout; pinFunctions: PinFunctionData } {
  const entry: CoreBoard = arduinoCoreBoards[boardId];
  const table = tableFromRows(entry.pins);
  const used = new Set<string>(Object.values(table).flatMap((row) => row.flags ?? []));
  return { pinout: withPinFunctions(pinout, table), pinFunctions: coreData(boardId, entry, used) };
}
