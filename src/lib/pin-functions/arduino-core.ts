function nrfFamily(
  sources: PinFunctionData["sources"],
  buses: { i2c: string[]; uart: string[]; spi: string[]; pwm: string[] },
): CustomFamily {
  return {
    sources,
    exports: ["c-header", "json"],
    flagNotes: {},
    mux: {
      model: "matrix",
      note: nrfMux,
      routable: [
        { peripheral: "I2C", instances: buses.i2c, signals: ["SDA", "SCL"] },
        { peripheral: "SPI", instances: buses.spi, signals: ["SCK", "MOSI", "MISO", "CS"] },
        { peripheral: "UART", instances: buses.uart, signals: ["TX", "RX"] },
        { peripheral: "PWM", instances: buses.pwm, signals: pwmChannels },
      ],
    },
  };
}

